    def _find_cross_file_instances(self, finding: Finding, context: RepoContext) -> dict[str, str]:
        """Find other files in the repo with the same issue pattern (X-Ray Vision via RAG).

        Uses ChromaDB semantic search to find code chunks related to the finding.
        Falls back to the old regex approach if ChromaDB is unavailable.
        """
        if not finding.file_path or not context.relevant_files:
            return {}

        # Build a semantic query from the finding
        query_parts = [finding.title]
        if finding.description:
            query_parts.append(finding.description[:200])
        if finding.suggestion:
            query_parts.append(finding.suggestion[:200])
        query_text = " ".join(query_parts)

        indexer = RepoIndexer()

        try:
            # Index all relevant files for semantic search
            chunk_count = indexer.index_repo(context.repo.full_name, context.relevant_files)
            if chunk_count == 0:
                return {}

            # Query for semantically related code chunks
            results = indexer.query_context(query_text, n_results=8)

            if not results:
                logger.warning(
                    "RAG query returned empty for '%s'. Falling back to regex extraction.",
                    finding.title,
                )
                return {}

            # Group by file and deduplicate
            other_files: dict[str, str] = {}
            seen_files: set[str] = set()
            for r in results:
                fpath = r["file_path"]
                if fpath == finding.file_path or fpath in seen_files:
                    continue
                if len(other_files) >= 3:
                    break
                other_files[fpath] = r["content"]
                seen_files.add(fpath)

            if other_files:
                logger.info(
                    "🔗 [RAG X-Ray] Found related context in %d other file(s): %s",
                    len(other_files),
                    ", ".join(other_files.keys()),
                )
            return other_files

        except Exception as exc:
            logger.warning(
                "RAG cross-file search failed for '%s', falling back to regex: %s",
                finding.title,
                exc,
            )
            # Fallback to old regex-based approach
            keywords = self._extract_search_patterns(finding)
            if not keywords:
                return {}

            other_files: dict[str, str] = {}
            for fpath, content in context.relevant_files.items():
                if fpath == finding.file_path:
                    continue
                content_lower = content.lower()
                matches = sum(1 for kw in keywords if kw.lower() in content_lower)
                if matches >= 2:
                    other_files[fpath] = content
                    if len(other_files) >= 3:
                        break

            if other_files:
                logger.info(
                    "🔗 [RAG fallback] Found same pattern in %d other file(s): %s",
                    len(other_files),
                    ", ".join(other_files.keys()),
                )
            return other_files
        finally:
            indexer.destroy()

    @staticmethod
    def _extract_search_patterns(finding: Finding) -> list[str]:
        """Extract code patterns from finding description to search across files.

        Looks for code-like tokens in the finding's description and suggestion.
        """
        patterns = []
        text = f"{finding.description} {finding.suggestion or ''}"
        # Extract backtick-quoted code snippets
        import re

        for match in re.findall(r"`([^`]+)`", text):
            if len(match) > 3:  # Skip very short matches
                patterns.append(match)
        # Extract common code patterns mentioned
        for pattern in re.findall(r"(\w+\.\w+[!?]?(?:\(\))?)", text):
            if len(pattern) > 5:
                patterns.append(pattern)
        return patterns[:10]  # Cap at 10 patterns

    def _replace_function_block(
        self, source_code: str, function_name: str, replacement: str, path: str
    ) -> str | None:
        """Replace an entire function/method block using AST or regex fallback.

        Uses Python's ``ast`` module for .py files to precisely locate
        function boundaries. For other languages, falls back to
        indentation-based heuristic matching.

        Args:
            source_code: Original file content.
            function_name: Name of the function to replace.
            replacement: New function content (will be re-indented to match).
            path: File path (used for language detection and logging).

        Returns:
            New file content string if replacement succeeded, None otherwise.
        """
        is_python = path.endswith(".py")

        if is_python:
            try:
                import ast as _ast

                tree = _ast.parse(source_code)
                func_nodes = [
                    node
                    for node in _ast.walk(tree)
                    if isinstance(node, (_ast.FunctionDef, _ast.AsyncFunctionDef))
                    and node.name == function_name
                ]
                if not func_nodes:
                    logger.debug("AST fallback: function '%s' not found in %s", function_name, path)
                    return None
                if len(func_nodes) > 1:
                    logger.debug(
                        "AST fallback: multiple functions named '%s' in %s, using first",
                        function_name,
                        path,
                    )
                target = func_nodes[0]
                if hasattr(target, "decorator_list") and target.decorator_list:
                    start_line = target.decorator_list[0].lineno - 1
                else:
                    start_line = target.lineno - 1

                lines = source_code.split("\n")

                end_line_idx = (
                    (target.end_lineno - 1)
                    if hasattr(target, "end_lineno") and target.end_lineno
                    else len(lines) - 1
                )

                orig_indent = (
                    lines[start_line][: len(lines[start_line]) - len(lines[start_line].lstrip())]
                    if start_line < len(lines) and lines[start_line].strip()
                    else ""
                )
                reindented_lines = []
                for rline in replacement.split("\n"):
                    if rline.strip():
                        reindented_lines.append(orig_indent + rline.lstrip())
                    else:
                        reindented_lines.append("")

                lines[start_line : end_line_idx + 1] = reindented_lines
                result = "\n".join(lines)
                logger.info(
                    "AST fallback replaced function '%s' in %s (lines %d-%d)",
                    function_name,
                    path,
                    start_line + 1,
                    end_line_idx + 1,
                )
                return result
            except SyntaxError:
                logger.debug(
                    "AST fallback: source has syntax errors, using regex fallback for %s", path
                )

        # Regex/heuristic fallback for non-Python files or broken Python
        # Matches: (async )?(def|function|fn|func|sub|proc|method)\s+FUNC_NAME
        func_pattern = re.compile(
            rf"(?:(?:async\s+|public\s+|private\s+|protected\s+|static\s+|virtual\s+|override\s+|internal\s+)*"
            rf"(?:def|function|fn|func|sub|proc|method)\s+"
            rf"{re.escape(function_name)}\s*[\(<{{])",
            re.IGNORECASE,
        )
        lines = source_code.split("\n")
        func_start = None
        for i, line in enumerate(lines):
            if func_pattern.search(line):
                func_start = i
                break

        if func_start is None:
            logger.debug("Regex fallback: function '%s' not found in %s", function_name, path)
            return None

        # Determine function indent from the definition line
        orig_indent = lines[func_start][: len(lines[func_start]) - len(lines[func_start].lstrip())]
        indent_level = len(orig_indent)

        # Find end of function: first line at same or less indent that is not blank
        # and is not a continuation/bracket line
        func_end = len(lines) - 1
        brace_depth = 0
        paren_depth = 0
        found_open = False
        for i in range(func_start, len(lines)):
            line = lines[i]
            stripped = line.lstrip()
            current_indent = len(line) - len(line.lstrip()) if stripped else indent_level + 1

            brace_depth += stripped.count("{") - stripped.count("}")
            paren_depth += stripped.count("(") - stripped.count(")")
            if "{" in stripped or ":" in stripped:
                found_open = True

            if i > func_start and found_open and brace_depth <= 0 and paren_depth <= 0:  # noqa: SIM102
                if current_indent <= indent_level and stripped:
                    func_end = i - 1
                    break

        # Re-indent replacement to match original function indent
        reindented_lines = []
        for rline in replacement.split("\n"):
            if rline.strip():
                reindented_lines.append(orig_indent + rline.lstrip())
            else:
                reindented_lines.append("")

        lines[func_start : func_end + 1] = reindented_lines
        result = "\n".join(lines)
        logger.info(
            "Regex fallback replaced function '%s' in %s (lines %d-%d)",
            function_name,
            path,
            func_start + 1,
            func_end + 1,
        )
        return result

    def _parse_changes(
        self,
        response: str,
        context: RepoContext,
        extra_file_contents: dict[str, str] | None = None,
    ) -> list[FileChange]:
        """Parse LLM response into FileChange objects.

        Supports three response formats:
        1. ``{"files": [...]}`` — multi-file array (preferred for cross-file patches).
           Each entry: ``{"file": "path", "is_new_file": false, "edits": [...]}``.
        2. ``{"changes": [...]}`` — single-file list (backward-compatible default).
        3. Full content — ``{"content": "..."}`` for new files.

        Args:
            response: Raw LLM response text.
            context: RepoContext with ``relevant_files`` for original content lookup.
            extra_file_contents: Additional {path: content} mapping for dependency
                files fetched during the Omniscient Eye step. Checked before
                ``context.relevant_files`` when looking up original file content.
        """
        import yaml

        changes: list[FileChange] = []

        try:
            cleaned_response = re.sub(
                r"<think>[\s\S]*?</think>",
                "",
                response,
                flags=re.IGNORECASE,
            ).strip()

            payload_text = None

            json_match = re.search(
                r"```json\s*\n(.*?)\n\s*```",
                cleaned_response,
                re.DOTALL | re.IGNORECASE,
            )
            if json_match:
                payload_text = json_match.group(1)
            else:
                json_match = re.search(
                    r"\{[\s\S]*?(?:\"changes\"|'changes'|\"files\"|'files')[\s\S]*\}",
                    cleaned_response,
                )
                if json_match:
                    payload_text = json_match.group(0)
                else:
                    yaml_match = re.search(
                        r"changes:\s*[\s\S]*",
                        cleaned_response,
                        re.IGNORECASE,
                    )
                    if yaml_match:
                        payload_text = yaml_match.group(0)

            if not payload_text:
                return []

            # Use bulletproof extractor — strips fences, sanitizes, falls back gracefully.
            extracted = _extract_core_payload(payload_text)
            if not extracted:
                logger.warning(
                    "[_parse_changes] Could not extract JSON structure from LLM response. "
                    "Payload preview (first 200 chars): %s",
                    payload_text[:200],
                )
                return []

            try:
                data = json.loads(extracted)
            except json.JSONDecodeError as je:
                # Provide specific error context for the retry loop.
                logger.warning(
                    "[_parse_changes] JSON parse failed: %s. Attempting YAML fallback.",
                    je,
                )
                try:
                    data = yaml.safe_load(extracted)
                except Exception as ye:
                    raise GenerationError(
                        f"LLM output failed both JSON and YAML parsing.\n"
                        f"JSON error: {je}\n"
                        f"YAML error: {ye}\n"
                        f"Raw payload (first 300 chars): {payload_text[:300]}"
                    ) from je

            if isinstance(data, dict):
                coding_plan = data.get("coding_plan")
                if coding_plan:
                    logger.info("[CoT] DEV Agent Plan: %s", coding_plan)

                # Multi-file path: {"files": [{"file": "path", "edits": [...]}]}
                files_list = data.get("files")
                if files_list and isinstance(files_list, list):
                    logger.info(
                        "[MultiFile] Detected 'files' array with %d entries",
                        len(files_list),
                    )
                    raw_changes = []
                    for entry in files_list:
                        if not isinstance(entry, dict):
                            continue
                        # Normalize "file" key → "path" for uniform processing
                        normalized = dict(entry)
                        if "file" in normalized and "path" not in normalized:
                            normalized["path"] = normalized.pop("file")
                        raw_changes.append(normalized)
                else:
                    raw_changes = data.get("changes", [])

            elif isinstance(data, list):
                raw_changes = data
            else:
                return []

            for item in raw_changes:
                if not isinstance(item, dict) or "path" not in item:
                    continue

                path = str(item["path"]).strip().strip("`\"'")
                is_new = item.get("is_new_file", False)

                # ── Discipline Protocol: Block scratchpad/note files ────────────
                if is_new:
                    _SCRATCHPAD_PATTERNS = (  # noqa: N806
                        "note",
                        "explore",
                        "exploration",
                        "scratchpad",
                        "temp_",
                        "tmp_",
                        "draft",
                        "wip_",
                        "thought",
                    )
                    path_lower = path.lower()
                    is_scratchpad = any(p in path_lower for p in _SCRATCHPAD_PATTERNS)
                    # Block .md/.txt placed in src/ or source/ directories
                    is_md_in_src = path_lower.startswith(
                        ("src/", "source/", "app/", "lib/")
                    ) and path_lower.endswith((".md", ".txt"))
                    if is_scratchpad or is_md_in_src:
                        logger.warning(
                            "🗑️ Discipline Protocol: rejecting new file '%s' "
                            "(scratchpad=%s, md_in_src=%s) — "
                            "non-code or note file in source dir is forbidden.",
                            path,
                            is_scratchpad,
                            is_md_in_src,
                        )
                        raise GenerationError(
                            f"Generator produced a forbidden scratchpad/note file: {path}"
                        )
                # ─────────────────────────────────────────────────────────────────

                if "edits" in item and not is_new:
                    # Search/replace mode — apply edits to original content.
                    # Check extra_file_contents (dependency files) first, then
                    # fall back to context.relevant_files (primary fetched files).
                    original = (extra_file_contents or {}).get(path) or context.relevant_files.get(
                        path, ""
                    )
                    if not original:
                        # New file via "edits" path: the LLM is writing to a
                        # file that doesn't exist yet (original is empty).
                        # Concatenate all replace blocks as the new file content,
                        # bypassing the strict search-matching constraints.
                        if any(e.get("replace") for e in item.get("edits", [])):
                            full_content = "\n".join(
                                e.get("replace", "") for e in item["edits"] if e.get("replace")
                            )
                            logger.info(
                                "[MultiFile] New file via edits path: %s (%d chars)",
                                path,
                                len(full_content),
                            )
                            changes.append(
                                FileChange(
                                    path=path,
                                    new_content=full_content,
                                    is_new_file=True,
                                )
                            )
                        else:
                            logger.warning(
                                "No original content for %s (finding file not fetched), skipping edits",  # noqa: E501
                                path,
                            )
                        continue

                    new_content = original
                    edits_applied = 0
                    edits_total = len(item["edits"])
                    for edit in item["edits"]:
                        search = edit.get("search", "")
                        replace = edit.get("replace", "")
                        if not search:
                            continue

                        matched = False

                        # Try 1: Exact match
                        if search in new_content:
                            new_content = new_content.replace(search, replace, 1)
                            matched = True

                        # Try 2: Relaxed Match
                        if not matched:
                            norm_search = "\n".join(
                                line.rstrip().replace("\t", "    ") for line in search.split("\n")
                            )
                            norm_content = "\n".join(
                                line.rstrip().replace("\t", "    ")
                                for line in new_content.split("\n")
                            )
                            if norm_search in norm_content:
                                idx = norm_content.index(norm_search)
                                start_line = norm_content[:idx].count("\n")
                                end_line = start_line + norm_search.count("\n")
                                lines = new_content.split("\n")
                                lines[start_line : end_line + 1] = replace.split("\n")
                                new_content = "\n".join(lines)
                                matched = True
                                logger.debug(
                                    "Fuzzy match (Relaxed Match) for %s",
                                    path,
                                )

                        # Try 3: Strip all leading/trailing whitespace
                        if not matched:
                            stripped_search = search.strip()
                            if len(stripped_search) > 20 and stripped_search in new_content:
                                new_content = new_content.replace(
                                    stripped_search, replace.strip(), 1
                                )
                                matched = True
                                logger.debug(
                                    "Fuzzy match (stripped) for %s",
                                    path,
                                )

                        # Try 4: Indentation-agnostic line-by-line matching
                        # Strips leading whitespace from each line for
                        # comparison, then re-applies the original file's
                        # indentation to the replacement block.
                        if not matched:
                            search_lines = search.split("\n")
                            content_lines = new_content.split("\n")
                            stripped_search_lines = [l.lstrip() for l in search_lines]  # noqa: E741

                            # Slide a window of len(search_lines) over content
                            window = len(search_lines)
                            if window >= 2:  # Require at least 2 lines for safety
                                for start_idx in range(len(content_lines) - window + 1):
                                    candidate = content_lines[start_idx : start_idx + window]
                                    candidate_stripped = [l.lstrip() for l in candidate]  # noqa: E741
                                    if candidate_stripped == stripped_search_lines:
                                        # Match found — re-indent replacement
                                        # using the original file's leading whitespace
                                        replace_lines = replace.split("\n")
                                        reindented: list[str] = []
                                        for j, rline in enumerate(replace_lines):
                                            if j < len(candidate):
                                                # Borrow indent from the corresponding original line
                                                orig_indent = candidate[j][
                                                    : len(candidate[j]) - len(candidate[j].lstrip())
                                                ]
                                            elif candidate:
                                                # Extra lines: use indent of the last matched line
                                                last = candidate[-1]
                                                orig_indent = last[: len(last) - len(last.lstrip())]
                                            else:
                                                orig_indent = ""
                                            # Strip the LLM's indent and apply the file's indent
                                            reindented.append(orig_indent + rline.lstrip())

                                        content_lines[start_idx : start_idx + window] = reindented
                                        new_content = "\n".join(content_lines)
                                        matched = True
                                        logger.debug(
                                            "Indent-agnostic match for %s (lines %d-%d)",
                                            path,
                                            start_idx + 1,
                                            start_idx + window,
                                        )
                                        break

                        # Try 5: Aggressive Indentation Normalization
                        if not matched:
                            search_lines = search.split("\n")
                            content_lines = new_content.split("\n")
                            stripped_search_lines = [l.strip() for l in search_lines]  # noqa: E741

                            window = len(search_lines)
                            if window >= 1:
                                for start_idx in range(len(content_lines) - window + 1):
                                    candidate = content_lines[start_idx : start_idx + window]
                                    candidate_stripped = [l.strip() for l in candidate]  # noqa: E741
                                    if candidate_stripped == stripped_search_lines:
                                        # Match found
                                        replace_lines = replace.split("\n")
                                        reindented: list[str] = []
                                        for j, rline in enumerate(replace_lines):
                                            if j < len(candidate):
                                                # Borrow indent from the corresponding original line
                                                orig_indent = candidate[j][
                                                    : len(candidate[j]) - len(candidate[j].lstrip())
                                                ]
                                            elif candidate:
                                                last = candidate[-1]
                                                orig_indent = last[: len(last) - len(last.lstrip())]
                                            else:
                                                orig_indent = ""
                                            reindented.append(orig_indent + rline.lstrip())

                                        content_lines[start_idx : start_idx + window] = reindented
                                        new_content = "\n".join(content_lines)
                                        matched = True
                                        logger.debug(
                                            "Aggressive indent normalization match for %s (lines %d-%d)",  # noqa: E501
                                            path,
                                            start_idx + 1,
                                            start_idx + window,
                                        )
                                        break

                        # Try 6: Blank-line-agnostic matching
                        # Removes all blank/whitespace-only lines from both
                        # search and content before comparing, then re-applies
                        # the replacement at the matched line range.
                        if not matched:
                            search_lines = search.split("\n")
                            content_lines = new_content.split("\n")

                            nonblank_search = [
                                (i, line_text)
                                for i, line_text in enumerate(search_lines)
                                if line_text.strip()
                            ]
                            nonblank_content = [
                                (i, line_text)
                                for i, line_text in enumerate(content_lines)
                                if line_text.strip()
                            ]

                            nb_search_stripped = [l.strip() for _, l in nonblank_search]  # noqa: E741
                            nb_content_stripped = [l.strip() for _, l in nonblank_content]  # noqa: E741

                            window_nb = len(nb_search_stripped)
                            if window_nb >= 2:
                                for start_nb in range(len(nb_content_stripped) - window_nb + 1):
                                    nb_candidate = nb_content_stripped[
                                        start_nb : start_nb + window_nb
                                    ]
                                    if nb_candidate == nb_search_stripped:
                                        orig_start = nonblank_content[start_nb][0]
                                        orig_end = nonblank_content[start_nb + window_nb - 1][0]

                                        replace_lines = replace.split("\n")
                                        base_indent = (
                                            content_lines[orig_start][
                                                : len(content_lines[orig_start])
                                                - len(content_lines[orig_start].lstrip())
                                            ]
                                            if content_lines[orig_start].strip()
                                            else ""
                                        )
                                        reindented: list[str] = []
                                        for j, rline in enumerate(replace_lines):
                                            if j < (
                                                orig_end - orig_start + 1
                                            ) and orig_start + j < len(content_lines):
                                                src_line = content_lines[orig_start + j]
                                                orig_indent = (
                                                    src_line[
                                                        : len(src_line) - len(src_line.lstrip())
                                                    ]
                                                    if src_line.strip()
                                                    else base_indent
                                                )
                                            else:
                                                orig_indent = base_indent
                                            reindented.append(
                                                orig_indent + rline.lstrip()
                                                if rline.strip()
                                                else ""
                                            )

                                        content_lines[orig_start : orig_end + 1] = reindented
                                        new_content = "\n".join(content_lines)
                                        matched = True
                                        logger.debug(
                                            "Blank-line-agnostic match for %s (lines %d-%d)",
                                            path,
                                            orig_start + 1,
                                            orig_end + 1,
                                        )
                                        break

                        # Try 7: AST/Function-level fallback using target_function
                        # If the LLM specified a target_function name and all
                        # string matching failed, find and replace the entire
                        # function block using AST (Python) or regex-based
                        # heuristics (other languages).
                        if not matched:
                            target_func = edit.get("target_function", "")
                            if target_func and len(replace.strip()) > 10:
                                func_result = self._replace_function_block(
                                    new_content,
                                    target_func,
                                    replace,
                                    path,
                                )
                                if func_result is not None:
                                    new_content = func_result
                                    matched = True

                        if matched:
                            # Diff Minimizer: detect edits where the LLM
                            # rewrote far more than it searched for — a sign
                            # of hallucinated full-function rewrites.
                            search_line_count = len(search.split("\n"))
                            replace_line_count = len(replace.split("\n"))
                            MAX_REPLACE_TO_SEARCH_RATIO = 100.0  # noqa: N806
                            if (
                                search_line_count > 0
                                and (replace_line_count / search_line_count)
                                > MAX_REPLACE_TO_SEARCH_RATIO
                            ):
                                logger.info(
                                    "Diff Minimizer: replace/search ratio %.1f exceeds limit %.1f in %s",  # noqa: E501
                                    replace_line_count / search_line_count,
                                    MAX_REPLACE_TO_SEARCH_RATIO,
                                    path,
                                )
                            if replace_line_count > 50:
                                logger.warning(
                                    "Diff Minimizer blocked: replace block too large "
                                    "(%d lines) in %s",
                                    replace_line_count,
                                    path,
                                )
                                continue
                            edits_applied += 1
                        else:
                            first_search_line = search.split("\n")[0].strip() if search else ""
                            closest_matches = []
                            for i, c_line in enumerate(new_content.split("\n")):
                                if first_search_line and first_search_line in c_line:
                                    closest_matches.append(f"line {i + 1}: '{c_line.strip()}'")

                            match_info = (
                                ", ".join(closest_matches[:3]) if closest_matches else "none"
                            )

                            logger.warning(
                                "Search text not found in %s (tried exact + fuzzy + indent-agnostic + aggressive). "  # noqa: E501
                                "Search line 1: '%s'. Closest matches in file: %s",
                                path,
                                first_search_line,
                                match_info,
                            )

                    logger.info(
                        "Edits for %s: %d/%d applied",
                        path,
                        edits_applied,
                        edits_total,
                    )

                    if edits_applied == 0:
                        logger.warning("No edits applied to %s, skipping file", path)
                        continue

                    changes.append(
                        FileChange(
                            path=path,
                            original_content=original,
                            new_content=new_content,
                            is_new_file=False,
                        )
                    )

                elif "content" in item:
                    # Full content mode (new files or fallback)
                    changes.append(
                        FileChange(
                            path=path,
                            new_content=item["content"],
                            is_new_file=is_new,
                        )
                    )

        except (json.JSONDecodeError, KeyError, TypeError) as e:
            logger.warning("Failed to parse changes JSON: %s", e)

        # Enforce max files limit
        if len(changes) > self._config.max_files_per_pr:
            logger.warning(
                "Too many files changed (%d > %d), truncating",
                len(changes),
                self._config.max_files_per_pr,
            )
            changes = changes[: self._config.max_files_per_pr]

        # ── Gag Order — Regex sanitizer against AI disclosures ───────────────
        for change in changes:
            for attr in ("new_content", "original_content"):
                val = getattr(change, attr, "") or ""
                if _GHOST_DISCLOSURE_RE.search(val):
                    logger.warning(
                        "🗑️ Gag Order triggered — AI disclosure detected in %s. "
                        "Aborting contribution for file %s.",
                        attr,
                        change.path,
                    )
                    raise GenerationError(
                        f"L LM output contains forbidden AI disclosure: {change.path}"
                    )
        # ─────────────────────────────────────────────────────────────────────

        return changes

    async def _generate_commit_message(
        self, finding: Finding, changes: list[FileChange], context: RepoContext
    ) -> str:
        """Generate a conventional commit message."""
        type_prefixes = {
            ContributionType.SECURITY_FIX: "fix(security)",
            ContributionType.CODE_QUALITY: "refactor",
            ContributionType.README_FIX: "docs",
            ContributionType.UI_UX_FIX: "fix(ui)",
            ContributionType.PERFORMANCE_OPT: "perf",
            ContributionType.FEATURE_ADD: "feat",
            ContributionType.REFACTOR: "refactor",
        }

        prefix = type_prefixes.get(finding.type, "fix")
        files = ", ".join(c.path.split("/")[-1] for c in changes[:3])

        if self._config.commit_convention == "conventional":
            # Try to extract scope from file path
            scope = ""
            if changes:
                parts = changes[0].path.split("/")
                if (len(parts) >= 2 and parts[0] in ("packages", "apps", "libs")) or (
                    len(parts) >= 2 and parts[0] == "src"
                ):
                    scope = parts[1]
            if scope:
                msg = (
                    f"{prefix}({scope}): {finding.title.lower()}\n\n"
                    f"{finding.description}\n\n"
                    f"Affected files: {files}"
                )
            else:
                msg = (
                    f"{prefix}: {finding.title.lower()}\n\n"
                    f"{finding.description}\n\n"
                    f"Affected files: {files}"
                )
        elif self._config.commit_convention == "angular":
            scope = changes[0].path.split("/")[0] if changes else ""
            msg = f"{prefix}({scope}): {finding.title.lower()}"
        else:
            msg = finding.title
        # ── Gag Order — sanitize commit message before use ──
        return _sanitize_text(msg, "commit message")

    def _generate_branch_name(self, finding: Finding) -> str:
        """Generate a clean branch name from finding."""
        prefix_map = {
            ContributionType.SECURITY_FIX: "fix/security",
            ContributionType.CODE_QUALITY: "improve/quality",
            ContributionType.README_FIX: "docs",
            ContributionType.UI_UX_FIX: "fix/ui",
            ContributionType.PERFORMANCE_OPT: "perf",
            ContributionType.FEATURE_ADD: "feat",
            ContributionType.REFACTOR: "refactor",
        }
        prefix = prefix_map.get(finding.type, "fix")
        # Clean title for branch name
        slug = re.sub(r"[^a-zA-Z0-9]+", "-", finding.title.lower()).strip("-")[:40]
        return f"{prefix}/{slug}"

    def _generate_pr_title(self, finding: Finding, *, guidelines=None) -> str:
        """Generate a PR title adapted to repo conventions."""
        # Use adaptive title if guidelines available
        if guidelines and guidelines.has_guidelines:
            from farm_agent.github.guidelines import (
                adapt_pr_title,
                extract_scope_from_path,
            )

            scope = extract_scope_from_path(finding.file_path or "", guidelines)
            return adapt_pr_title(
                finding.title,
                finding.type.value,
                guidelines,
                scope=scope,
            )

        # Default: emoji format — "Security" is rebranded as "Reliability" per Gag Order
        type_labels = {
            ContributionType.SECURITY_FIX: "🔒 Reliability",
            ContributionType.CODE_QUALITY: "✨ Quality",
            ContributionType.README_FIX: "📝 Docs",
            ContributionType.UI_UX_FIX: "🎨 UI/UX",
            ContributionType.PERFORMANCE_OPT: "⚡ Performance",
            ContributionType.FEATURE_ADD: "🚀 Feature",
            ContributionType.REFACTOR: "♻️ Refactor",
        }
        label = type_labels.get(finding.type, "🔧 Fix")
        # Apply security-word disguise to title as well
        safe_title = _sanitize_text(finding.title, "PR title")
        return f"{label}: {safe_title}"

    async def _self_review(self, contribution: Contribution, context: RepoContext) -> bool:
        """Have the LLM self-review the generated contribution."""
        changes_summary = "\n".join(
            f"- {c.path} ({'new' if c.is_new_file else 'modified'})" for c in contribution.changes
        )

        prompt = (
            "Review the following code contribution for quality:\n\n"
            f"**Title**: {contribution.title}\n"
            f"**Type**: {contribution.contribution_type.value}\n"
            f"**Finding**: {contribution.finding.description}\n"
            f"**Changes**:\n{changes_summary}\n\n"
            "For each changed file:\n"
        )
        for change in contribution.changes[:5]:
            review_snippet = self._build_review_snippet(change)
            prompt += f"\n### {change.path}\n```diff\n{review_snippet}\n```\n"

        prompt += (
            "\nAnswer these questions:\n"
            "1. Does the change correctly fix the described issue?\n"
            "2. Does it introduce any new bugs or security issues?\n"
            "3. Does it follow good coding practices?\n"
            "4. Is the change minimal and focused?\n\n"
            "Reply with APPROVE or REJECT followed by brief reasoning."
        )

        try:
            response = await self._llm.complete(prompt, temperature=0.1)
            response_upper = response.upper()
            if "REJECT" in response_upper:
                logger.info("Self-review rejected: %s", response[:200])
                return False
            if "APPROVE" in response_upper:
                return True
            logger.warning(
                "Self-review returned unrecognized verdict, approving by default: %s",
                response[:200],
            )
            return True
        except Exception as e:
            logger.warning("Self-review failed, approving by default: %s", e)
            return True  # Don't block on review failures

    @staticmethod
    def _build_review_snippet(change: FileChange, max_chars: int = 2000) -> str:
        """Build a compact diff-oriented review snippet for self-review."""
        if change.original_content is not None:
            diff = "".join(
                difflib.unified_diff(
                    change.original_content.splitlines(keepends=True),
                    change.new_content.splitlines(keepends=True),
                    fromfile=f"a/{change.path}",
                    tofile=f"b/{change.path}",
                    n=3,
                )
            ).strip()
            if diff:
                return diff[:max_chars]

        return change.new_content[:max_chars]
