    async def fix_contribution_from_error(
        self,
        contribution: Contribution,
        context: RepoContext,
        error_log: str,
    ) -> Contribution | None:
        """Self-correct a broken patch using the CI/test error log.

        Called by the pipeline when DockerSandbox reports test/compile failures.
        Prompts the LLM to analyze the error and produce a corrected patch.

        Args:
            contribution: The failed contribution (with original finding).
            context: RepoContext with file contents and repo metadata.
            error_log: The sandbox stdout/stderr from the failed test run.

        Returns:
            A new Contribution with a corrected patch, or None on failure.

        Raises:
            GenerationError: If the LLM output contains an AI disclosure
                or the corrected patch is still invalid.
        """
        logger.info(
            "🔧 Self-Correcting patch for '%s' using error log (%.200s)",
            contribution.title,
            error_log[:200],
        )

        # Build a focused prompt for the LLM
        error_context = (
            f"The following CI/test run FAILED with this output:\n\n"
            f"=== ERROR LOG ===\n{error_log}\n"
            f"=== END ERROR LOG ===\n\n"
            f"Your previous patch was incorrect. Please analyze the error above "
            f"and produce a corrected patch for the same finding.\n"
            f"Finding: {contribution.finding.description}\n"
            f"File: {contribution.changes[0].path if contribution.changes else 'unknown'}\n"
        )

        system = self._build_system_prompt(context)
        prompt = (
            f"{error_context}\n\n"
            f"--- Repository Context (do NOT make changes outside the relevant files) ---\n"
            f"Relevant files:\n"
            + "\n".join(
                f"File: {fp}\nContent:\n{content[:3000]}"
                for fp, content in context.relevant_files.items()
            )
        )

        # Ask LLM for corrected patch
        raw = await self._llm.complete(prompt, system=system, temperature=0.2)
        text = (raw or "").strip()

        # Gag Order check on raw LLM output (before parsing)
        if _GHOST_DISCLOSURE_RE.search(text):
            raise GenerationError(
                "Gag Order: LLM output in fix_contribution_from_error "
                "contains AI disclosure — aborting self-correction."
            )

        # Parse the corrected changes
        import json as _json

        try:
            parsed = _json.loads(text)
        except _json.JSONDecodeError:
            # Try to extract JSON from markdown fences
            import re as _re

            stripped = _re.sub(r"```(?:json)?\s*", "", text, flags=_re.IGNORECASE)
            stripped = _re.sub(r"```\s*$", "", stripped)
            try:
                parsed = _json.loads(stripped)
            except _json.JSONDecodeError as je:
                raise GenerationError(
                    f"fix_contribution_from_error: could not parse LLM response as JSON: {je}"
                ) from je

        # ── Inline Gag Order on parsed changes ─────────────────────────────
        _gag_check_fields = ["new_content", "original_content"]
        for item in parsed.get("changes", []):
            for field in _gag_check_fields:
                val = item.get(field, "") or ""
                if _GHOST_DISCLOSURE_RE.search(val):
                    raise GenerationError(
                        f"Gag Order: corrected patch contains AI disclosure in '{field}' — aborting."  # noqa: E501
                    )
        # ─────────────────────────────────────────────────────────────────

        # Parse changes inline (same logic as _parse_changes but self-contained)
        from farm_agent.core.models import FileChange

        corrected_changes: list[FileChange] = []
        for item in parsed.get("changes", []):
            path = str(item.get("path", "")).strip().strip("`\"'")
            is_new = item.get("is_new_file", False)

            if is_new:
                continue  # skip new files in self-correction

            if "edits" not in item:
                continue

            for edit_block in item["edits"]:
                search = edit_block.get("search", "") or ""
                replace = edit_block.get("replace", "") or ""
                if search == replace:
                    raise GenerationError(
                        "fix_contribution_from_error: corrected patch is a no-op "
                        "(search == replace) — aborting."
                    )

            fc = FileChange(
                path=path,
                original_content=context.relevant_files.get(path, ""),
                new_content=item.get("new_content", ""),
            )
            corrected_changes.append(fc)

        contribution.changes = corrected_changes
        logger.info(
            "✅ Self-Correction succeeded for '%s' — %d file(s) corrected",
            contribution.title,
            len(corrected_changes),
        )
        return contribution

