def _extract_core_payload(raw_text: str) -> str | None:
    """Bulletproof JSON/payload extractor. Strips markdown, sanitizes, falls back.

    Handles LLM quirks: markdown code fences, conversational preamble,
    trailing commas, unescaped quotes, and common JSON malformations.
    """
    import ast
    import re as _re

    # Rule 1: Extract content from all markdown code fences.
    # Pick the largest fenced block — that's the actual payload.
    fences = _re.findall(r"```(?:\w*)\s*\n?(.*?)\n?\s*```", raw_text, _re.DOTALL | _re.IGNORECASE)
    if fences:
        raw_text = max(fences, key=len)

    # Rule 2: Strip conversational text before the first JSON opener.
    match = _re.search(r"[\[{]", raw_text)
    if match:
        raw_text = raw_text[match.start() :]

    # Rule 3: Sanitize common JSON malformations.
    # Remove trailing commas before ] or }.
    sanitized = _re.sub(r",(\s*[}\]])", r"\1", raw_text)
    # Remove unescaped quotes inside strings (a common LLM mistake).
    # We do NOT do aggressive unescaping — we only fix structural issues.

    try:
        json.loads(sanitized)
        return sanitized
    except json.JSONDecodeError:
        pass

    # Rule 4: Fallback to ast.literal_eval for loose parsing.
    try:
        ast.literal_eval(sanitized)
        return sanitized
    except (ValueError, SyntaxError):
        pass

    # Rule 5: Last resort — return the stripped text and let caller handle.
    return raw_text if raw_text.strip().startswith("{") else None


class ContributionGenerator:
    """Generate code contributions from analysis findings."""

    def __init__(
        self, llm: LLMProvider, config: ContributionConfig, *, memory=None, pipeline_config=None
    ):
        self._llm = llm
        self._config = config
        self._memory = memory  # Optional Memory for repo_preferences
        # Configurable patch retry limit (from PipelineConfig or default)
        self._max_patch_retries = (
            getattr(pipeline_config, "max_patch_retries", 2) if pipeline_config else 2
        )
        # Adversarial Reviewer — completely independent entity with its own LLM (qwen/qwen3.7-max)
        import copy

        from farm_agent.llm.provider import create_llm_provider

        reviewer_cfg = copy.copy(llm.config)
        reviewer_cfg.provider = "openrouter"
        reviewer_cfg.model = "qwen/qwen3.7-max"
        self._reviewer_llm = create_llm_provider(reviewer_cfg)
        self._reviewer = ReviewerAgent(self._reviewer_llm, max_review_tokens=800)
        # Repo mapper — generates structural skeleton + dependency graphs
        self._repo_mapper = RepoMapper()

    async def close(self):
        """Clean up independent reviewer LLM provider."""
        if hasattr(self, "_reviewer_llm") and self._reviewer_llm:
            await self._reviewer_llm.close()

    async def generate(
        self,
        finding: Finding,
        context: RepoContext,
        *,
        guidelines=None,
        github_client=None,
    ) -> Contribution | None:
        """Generate a contribution for a single finding.

        Steps:
        1. Build context-aware prompt
        2. Get LLM to generate the fix
        3. Parse structured output into FileChanges
        4. Generate commit message
        5. Self-review the generated code
        """
        import asyncio

        try:
            # 0: Fetch repo style from merged PRs (optional)
            async def _fetch_style() -> str:
                if github_client is None:
                    return ""
                try:
                    prs_data = await github_client.get_recent_merged_prs(
                        context.repo.owner,
                        context.repo.name,
                    )
                    from farm_agent.llm.context import extract_style_guide

                    return extract_style_guide(prs_data)
                except Exception as exc:
                    logger.debug("Style mimicry skipped: %s", exc)
                    return ""

            # 0.5: Generate project skeleton map for architectural awareness
            async def _fetch_map() -> str:
                if github_client is None:
                    return ""
                try:
                    mapper = RepoMapper()

                    async def _fetch(path: str) -> str:
                        content = await github_client.get_file_content(
                            context.repo.owner,
                            context.repo.name,
                            path,
                        )
                        context.relevant_files[path] = content
                        return content

                    return await mapper.generate_map(context.file_tree, _fetch)
                except Exception as exc:
                    logger.debug("Project map generation skipped: %s", exc)
                    return ""

            # Concurrent fetching to overclock system pipeline
            style_task = asyncio.create_task(_fetch_style())
            map_task = asyncio.create_task(_fetch_map())
            prefs_task = asyncio.create_task(self._get_repo_preferences(context))

            style_guide, project_map, repo_prefs = await asyncio.gather(
                style_task, map_task, prefs_task
            )

            # ── Diplomat Protocol Task 2: Merge RepoStyleGuide into style_guide ──
            if guidelines and hasattr(guidelines, "style_guide") and guidelines.style_guide:
                repo_style_prompt = guidelines.style_guide.to_prompt_section()
                if repo_style_prompt:
                    style_guide = (
                        f"{style_guide}\n\n{repo_style_prompt}"
                        if style_guide
                        else repo_style_prompt
                    )

            # ── P0-1 GRACEFUL CONTEXT FALLBACK — 3-tier rescue before aborting ─────────
            # The generator MUST have the actual source file content. Without it,
            # the LLM would hallucinate edits against an empty context.
            # TIER 1: Already-fetched file content (RAG/ChromaDB success)
            target_file_content = context.relevant_files.get(finding.file_path)

            # TIER 2: Explicit GitHubClient fetch (RAG was empty but we can still get the file)
            if not target_file_content and github_client is not None and finding.file_path:
                logger.warning(
                    "RAG miss for '%s' — attempting direct GitHub fetch for '%s'.",
                    finding.title,
                    finding.file_path,
                )
                try:
                    direct_content = await github_client.get_file_content(
                        context.repo.owner,
                        context.repo.name,
                        finding.file_path,
                    )
                    if direct_content:
                        context.relevant_files[finding.file_path] = direct_content
                        target_file_content = direct_content
                        logger.info(
                            "Tier-2 GitHub fetch succeeded for '%s' — context recovered.",
                            finding.file_path,
                        )
                except Exception as gh_exc:
                    logger.debug(
                        "Tier-2 GitHub fetch failed for '%s': %s",
                        finding.file_path,
                        gh_exc,
                    )

            # TIER 3: Deduce file from project_map (last resort before aborting)
            if not target_file_content and project_map and finding.file_path:
                logger.warning(
                    "RAG miss and GitHub fetch failed for '%s' — "
                    "scanning project_map for clues about '%s'.",
                    finding.title,
                    finding.file_path,
                )
                # The project_map is a structural overview — scan it for the target file
                # to confirm the file exists in the repo even if we cannot fetch it
                map_lower = project_map.lower()
                target_lower = finding.file_path.lower()
                if target_lower in map_lower or any(  # noqa: SIM102
                    segment in map_lower for segment in [finding.file_path]
                ):
                    # The file IS in the repo (confirmed by map), but we still cannot
                    # fetch it — try one more explicit fetch with a fallback path
                    if github_client is not None:
                        for path_variant in [
                            finding.file_path,
                            finding.file_path.lstrip("/"),
                            finding.file_path.replace("//", "/"),
                        ]:
                            try:
                                fallback_content = await github_client.get_file_content(
                                    context.repo.owner,
                                    context.repo.name,
                                    path_variant,
                                )
                                if fallback_content:
                                    context.relevant_files[finding.file_path] = fallback_content
                                    target_file_content = fallback_content
                                    logger.info(
                                        "Tier-3 map-assisted fetch succeeded for '%s'.",
                                        finding.file_path,
                                    )
                                    break
                            except Exception:
                                continue

            # ABORT only if ALL 3 tiers failed
            if not target_file_content:
                logger.error(
                    "ContextMissingError: no file content for '%s' (path='%s') — "
                    "RAG returned empty, GitHub fetch failed, and project_map "
                    "could not locate the file. "
                    "ABORTING generation to prevent blind code hallucination.",
                    finding.title,
                    finding.file_path,
                )
                raise ContextMissingError(
                    f"No usable context for target file: {finding.file_path}. "
                    f"Tier-1 (RAG): miss, Tier-2 (GitHub fetch): failed, "
                    f"Tier-3 (project_map): could not confirm file location. "
                    f"Generation is BLOCKED."
                )
            # ─────────────────────────────────────────────────────────────────────────────

            # 1 & 2: Generate the fix via agentic loop
            prompt = self._build_generation_prompt(finding, context, repo_prefs=repo_prefs)
            system = self._build_system_prompt(
                context,
                style_guide=style_guide,
                project_map=project_map,
            )

            if self._memory:
                try:
                    filter_lessons = await self._memory.get_knowledge(
                        context.repo.full_name, "FILTER_REJECTION_LESSON"
                    )
                    if filter_lessons:
                        system += (
                            f"\n\n### PREVIOUS MISTAKES TO AVOID ON THIS REPO:\n{filter_lessons}\n"
                        )
                except Exception as exc:
                    logger.debug("Could not fetch filter lessons for generator: %s", exc)

            response = await self._agentic_generate(
                prompt,
                system=system,
                github_client=github_client,
                context=context,
            )

            # 3: Parse output → apply search/replace to original content
            # Patch-Correction Retry Loop: if the patcher fails to apply
            # any edits (LLM hallucinated the SEARCH block), re-prompt the
            # LLM with the file content and ask for a corrected patch.
            MAX_PATCH_RETRIES = self._max_patch_retries  # noqa: N806
            changes = self._parse_changes(response, context)
            patch_attempt = 0
            while not changes and patch_attempt < MAX_PATCH_RETRIES:
                patch_attempt += 1
                logger.warning(
                    "Patch attempt %d/%d failed for %s — re-prompting LLM",
                    patch_attempt,
                    MAX_PATCH_RETRIES,
                    finding.title,
                )
                # Build a correction prompt with the actual file content
                file_content = context.relevant_files.get(finding.file_path, "")
                retry_prompt = (
                    "Your previous SEARCH block was NOT FOUND in the file. "
                    "This usually happens because of hallucinated lines, "
                    "incorrect indentation, or using `...` to skip lines.\n\n"
                    "Here is the ACTUAL file content you must match against:\n"
                    f"```\n{file_content[:6000]}\n```\n\n"
                    "Please review and provide the EXACT, VERBATIM block of code "
                    "you want to replace. Copy it character-for-character from the "
                    "file above. Do not use `...` to skip lines. Do not modify "
                    "indentation or whitespace.\n\n" + prompt  # Re-include the original task prompt
                )
                response = await self._agentic_generate(
                    retry_prompt,
                    system=system,
                    github_client=github_client,
                    context=context,
                )
                changes = self._parse_changes(response, context)

            if not changes:
                logger.warning("No valid changes parsed for finding: %s", finding.title)
                return None

            # ── Sanity Check: Abort if patch is a no-op ──────────────────────
            for change in changes:
                if change.is_new_file:
                    continue  # new files are OK
                # Check if the change only touches comments/whitespace (replace === search)
                if hasattr(change, "edits") and change.edits:
                    for edit in change.edits:
                        search = getattr(edit, "search", "") or ""
                        replace = getattr(edit, "replace", "") or ""
                        # Both empty → no-op; Both identical → no functional change
                        if search == replace:
                            logger.warning(
                                "🗑️ Sanity check FAILED for '%s' — patch is a no-op "
                                "(search == replace). Aborting PR.",
                                finding.title,
                            )
                            return None
            # ──────────────────────────────────────────────────────────────────

            # 4: Generate commit message
            commit_msg = await self._generate_commit_message(finding, changes, context)

            # 5: Generate branch name
            branch_name = self._generate_branch_name(finding)

            # Build the contribution
            contribution = Contribution(
                finding=finding,
                contribution_type=finding.type,
                title=self._generate_pr_title(finding, guidelines=guidelines),
                description=finding.description,
                changes=changes,
                commit_message=commit_msg,
                branch_name=branch_name,
                generated_at=datetime.now(UTC),
            )

            # 6: Adversarial review loop — paranoid Senior Security Auditor
            # If the reviewer REJECTs, the Generator rewrites with the critique.
            # This is a completely SEPARATE entity from the Generator — no shared history.
            review_attempt = 0
            max_review_retries = self._config.max_review_retries
            latest_contribution = contribution
            latest_changes = changes

            while review_attempt <= max_review_retries:
                verdict = await self._reviewer.review(latest_contribution, context)
                if verdict["decision"] == "APPROVE":
                    logger.info(
                        "Adversarial review PASSED for: %s (attempt %d)",
                        finding.title,
                        review_attempt + 1,
                    )
                    break

                critique = verdict["critique"]
                logger.warning(
                    "🔴 Adversarial review REJECTED for: %s — attempt %d/%d",
                    finding.title,
                    review_attempt + 1,
                    max_review_retries + 1,
                )
                if critique:
                    logger.info("Critique: %s", critique[:300])

                if review_attempt >= max_review_retries:
                    # All retries exhausted — discard this finding to protect the repo
                    logger.error(
                        "🛑 Adversarial Review Failed for '%s' — discarding finding after %d attempts. "  # noqa: E501
                        "The patch was not good enough to pass our security audit.",
                        finding.title,
                        max_review_retries + 1,
                    )
                    return None

                # Rewrite with critique appended to the prompt
                review_attempt += 1
                logger.info("Rewriting patch with critique (attempt %d)...", review_attempt)

                # Build rewrite prompt: append critique to original generation prompt
                rewrite_prompt = self._build_generation_prompt(
                    finding,
                    context,
                    repo_prefs=repo_prefs,
                    adversarial_critique=critique,
                )
                response = await self._agentic_generate(
                    rewrite_prompt,
                    system=system,
                    github_client=github_client,
                    context=context,
                )
                latest_changes = self._parse_changes(response, context)
                if not latest_changes:
                    logger.warning(
                        "Rewrite attempt produced no valid changes for: %s", finding.title
                    )
                    return None

                # Regenerate commit message and branch name for the rewritten patch
                new_commit_msg = await self._generate_commit_message(
                    finding, latest_changes, context
                )
                new_branch_name = self._generate_branch_name(finding)

                latest_contribution = Contribution(
                    finding=finding,
                    contribution_type=finding.type,
                    title=self._generate_pr_title(finding, guidelines=guidelines),
                    description=finding.description,
                    changes=latest_changes,
                    commit_message=new_commit_msg,
                    branch_name=new_branch_name,
                    generated_at=datetime.now(UTC),
                )

            logger.info(
                "Generated contribution: %s (%d files changed)",
                contribution.title,
                contribution.total_files_changed,
            )
            return contribution

        except Exception as e:
            logger.error("Failed to generate contribution for %s: %s", finding.title, e)
            return None

    # ── Bloodhound-driven Generation with Anti-Template Interceptor ────────

    async def generate_from_dossier(
        self,
        dossier: VulnerabilityDossier,
        context: RepoContext,
        *,
        guidelines=None,
        github_client=None,
        failure_context: str = "",
    ) -> GenerationResult:
        """Generate patches for vulnerabilities found by the Bloodhound analyzer.

        Uses a 3-cycle retry loop with a regex interceptor that catches
        lazy LLM outputs (placeholders, TODOs, ellipsis, etc.) and forces
        automatic retries with escalating warnings.

        Injects QA lessons from memory to avoid repeating past mistakes.
        Injects failure_context from previous DEV-QA cycles so the LLM
        can read raw compilation/test errors and QA critiques.

        Args:
            dossier: VulnerabilityDossier from BloodhoundAnalyzer.
            context: RepoContext with file contents for the target repo.
            guidelines: Optional repo guidelines.
            github_client: Optional GitHub client for file reads.
            failure_context: Accumulated failure traces from previous DEV-QA
                cycles (QA critiques, sandbox stderr, generation errors).

        Returns:
            GenerationResult with contributions list and false_positive_count.
        """
        contributions: list[Contribution] = []
        false_positive_count = 0

        for vuln in dossier.vulnerabilities:
            if vuln.file == "NONE":
                logger.info("Skipping NONE vulnerability marker in dossier")
                continue

            result = await self._generate_single_vuln(
                vuln=vuln,
                dossier=dossier,
                context=context,
                guidelines=guidelines,
                github_client=github_client,
                failure_context=failure_context,
            )
            if result is None:
                false_positive_count += 1
            elif result is not None:
                contributions.append(result)

        logger.info(
            "Generated %d/%d contributions from dossier for %s (false positives: %d)",
            len(contributions),
            len(dossier.vulnerabilities),
            dossier.repo_url,
            false_positive_count,
        )
        return GenerationResult(
            contributions=contributions,
            false_positive_count=false_positive_count,
        )

    async def _generate_single_vuln(
        self,
        vuln: Vulnerability,
        dossier: VulnerabilityDossier,
        context: RepoContext,
        *,
        guidelines=None,
        github_client=None,
        failure_context: str = "",
    ) -> Contribution | None:
        """Generate a single Contribution for one Vulnerability entry.

        Implements the 3-cycle anti-template retry loop with QA lesson injection.
        Injects failure_context from previous DEV-QA cycles so the LLM can read
        raw compilation/test errors and QA critiques.
        """
        # ── Inject QA Lessons from knowledge base ────────────────────────
        qa_lessons_section = ""
        if self._memory is not None:
            try:
                qa_lessons = await self._memory.get_qa_lessons(dossier.repo_url)
                if qa_lessons:
                    qa_lessons_section = (
                        "\n\nPAST QA LESSONS (Avoid these mistakes at all costs):\n"
                        + "\n".join(f"- {lesson}" for lesson in qa_lessons)
                        + "\n"
                    )
            except Exception as exc:
                logger.debug("Could not fetch QA lessons: %s", exc)

            try:
                filter_lessons = await self._memory.get_knowledge(
                    context.repo.full_name, "FILTER_REJECTION_LESSON"
                )
                if filter_lessons:
                    qa_lessons_section += (
                        f"\n\n### PREVIOUS MISTAKES TO AVOID ON THIS REPO:\n{filter_lessons}\n"
                    )
            except Exception as exc:
                logger.debug("Could not fetch filter lessons: %s", exc)

        # ── Build hardened system prompt ─────────────────────────────────
        system = (
            "You are an elite, silent software engineer. "
            "You MUST think deeply before writing any code.\n\n"
            "ABSOLUTE RULES:\n"
            "1. Before writing any code, you MUST formulate a strict, step-by-step "
            "architectural plan.\n"
            "2. Think about: root cause analysis, data flow, potential regressions, "
            "and how to neutralize the vulnerability without breaking the system.\n"
            "3. Every code block must be COMPLETE and FUNCTIONAL.\n"
            "4. STRICT NO-PLACEHOLDER POLICY. You are FORBIDDEN from using `// ...`, `TODO`, or any comments implying 'code remains the same'. You MUST output the ENTIRE function or block you are modifying.\n"  # noqa: E501
            "5. SURGICAL PRECISION: make the SMALLEST change that fixes the issue.\n"
            "6. Match existing code style EXACTLY (indentation, naming, patterns).\n"
            "7. Return ONLY the JSON object below. No prose, no markdown commentary, no \u0422\u0435\u0442\u0430\u0434\u0435 tags.\n"  # noqa: E501
            "8. CRITICAL: ABSOLUTELY NO TRUNCATION. YOU MUST OUTPUT THE ENTIRE MODIFIED FUNCTION OR BLOCK. "  # noqa: E501
            'NEVER USE "..." OR "# TODO". YOUR PATCH WILL BE AUTOMATICALLY REJECTED AND YOU WILL BE '  # noqa: E501
            "PENALIZED IF YOU OMIT ANY ORIGINAL CODE.\n"
        )

        # ── Build user prompt from vulnerability ─────────────────────────
        target_file_content = context.relevant_files.get(vuln.file, "")

        # Try to fetch the file if we don't have it
        if not target_file_content and github_client is not None and vuln.file:
            logger.warning("Context miss for '%s' — attempting direct fetch.", vuln.file)
            try:
                direct_content = await github_client.get_file_content(
                    context.repo.owner,
                    context.repo.name,
                    vuln.file,
                )
                if direct_content:
                    context.relevant_files[vuln.file] = direct_content
                    target_file_content = direct_content
                    logger.info("Direct fetch succeeded for '%s'.", vuln.file)
            except Exception as exc:
                logger.debug("Direct fetch failed for '%s': %s", vuln.file, exc)

        if not target_file_content:
            logger.error(
                "No file content for '%s' — cannot generate patch for vuln at line %d",
                vuln.file,
                vuln.line,
            )
            return None

        # ── Omniscient Eye: build skeleton + dependency context ───────────
        _repo_skeleton = ""
        _dependency_files: dict[str, str] = {}
        if context.relevant_files:
            try:
                _repo_skeleton = self._repo_mapper.generate_repo_skeleton(
                    context.relevant_files,
                )
                _deps = self._repo_mapper.resolve_file_dependencies(
                    vuln.file,
                    context.relevant_files,
                )
                _dep_paths = (_deps["imports"] + _deps["callers"])[:3]
                _dependency_files = {
                    p: context.relevant_files[p] for p in _dep_paths if p in context.relevant_files
                }
                if _dep_paths:
                    logger.info(
                        "🔭 Omniscient Eye: imports=%s callers=%s",
                        _deps["imports"],
                        _deps["callers"],
                    )
            except Exception as _exc:
                logger.debug("Omniscient Eye skipped: %s", _exc)
        # ─────────────────────────────────────────────────────────────────

        user_prompt = (
            f"## Task\n"
            f"Fix a SECURITY vulnerability in {context.repo.full_name}.\n\n"
            f"## Vulnerability Details\n"
            f"- **File**: {vuln.file}\n"
            f"- **Line**: {vuln.line}\n"
            f"- **Snippet**: {vuln.snippet}\n"
            f"- **Proof of Concept**: {vuln.poc}\n"
            f"- **Impact**: {vuln.impact}\n"
            f"- **Suggested Fix**: {vuln.fix}\n"
        )

        if qa_lessons_section:
            user_prompt += qa_lessons_section

        if failure_context:
            user_prompt += (
                "\n\n## Previous Failure Trace (MUST address these errors)\n"
                "Your previous attempt(s) failed. Here are the EXACT errors and critiques:\n"
                f"```\n{failure_context}\n```\n\n"
                "You MUST analyze these failures and produce a DIFFERENT approach. "
                "Do NOT repeat the same mistakes.\n"
            )

        user_prompt += (
            f"\n## Current File Content ({vuln.file})\n```\n{target_file_content[:8000]}\n```\n\n"
        )

        # ── Related dependency files ──────────────────────────────────────
        if _dependency_files:
            user_prompt += (
                "## Related Files (direct imports / callers)\n"
                "These files share interfaces with the target. "
                "Do NOT re-implement helpers that already exist here.\n\n"
            )
            for dep_path, dep_content in _dependency_files.items():
                safe_path = _STRIP_AI_RE.sub("[sanitized]", dep_path)
                safe_content = _STRIP_AI_RE.sub("[AI-disclosure redacted]", dep_content[:4000])
                user_prompt += f"### {safe_path}\n```\n{safe_content}\n```\n\n"

        # ── Repo skeleton ─────────────────────────────────────────────────
        if _repo_skeleton:
            user_prompt += (
                "## Repository Skeleton (discover existing helpers before writing new code)\n"
                f"```\n{_repo_skeleton[:6000]}\n```\n\n"
            )

        user_prompt += (
            f"## Output Format\n"
            f"You MUST respond strictly in the following JSON format. "
            f"The `coding_plan` MUST appear first.\n"
            f'```json\n{{\n  "coding_plan": "1. Root cause analysis\\n2. Step-by-step fix strategy\\n3. Edge cases to handle",\n'  # noqa: E501
            f'  "changes": [\n    {{\n      "path": "{vuln.file}",\n'
            f'      "is_new_file": false,\n      "edits": [\n        {{\n'
            f'          "search": "exact text to find in the file",\n'
            f'          "replace": "replacement text",\n'
            f'          "target_function": ""\n        }}\n      ]\n    }}\n  ]\n}}\n```\n\n'
            f"CRITICAL:\n"
            f"- The `coding_plan` field is MANDATORY. Think before you code.\n"
            f"- The `search` value MUST be an EXACT, VERBATIM copy of text from the file above.\n"
            f"- NEVER use `...` or any placeholder to skip lines.\n"
            f"- Include enough context (3-5 lines) so the search block is unique.\n"
            f"- The `target_function` field is OPTIONAL. If provided, it specifies the function\n"
            f"  name to replace entirely if the `search` block fails to match. Use this as a\n"
            f"  safety net when modifying functions — set it to the function name being changed.\n"
            f"\nMULTI-FILE EDITS: If the fix requires changes across multiple files, use the\n"
            f'`"files"` array format instead of `"changes"`:\n'
            f'```json\n{{"coding_plan": "...", "files": [\n'
            f'  {{"file": "path/to/fileA.py", "is_new_file": false,\n'
            f'   "edits": [{{"search": "...", "replace": "...", "target_function": ""}}]}},\n'
            f'  {{"file": "path/to/fileB.py", "is_new_file": false,\n'
            f'   "edits": [{{"search": "...", "replace": "...", "target_function": ""}}]}}\n'
            f"]}}\n```\n"
            f"Apply the same SEARCH/REPLACE rules to each file entry.\n"
            f"\nCRITICAL: You are an automated system. Output ONLY the raw JSON structure. "
            f"Do NOT wrap your answer in markdown code blocks. Do NOT add greetings, "
            f"explanations, or conversational text. Start directly with {{ and end there.\n"
        )

        # ── 3-Cycle Anti-Template Retry Loop ──────────────────────────────
        MAX_CYCLES = 3  # noqa: N806
        retry_warning = ""

        for cycle in range(MAX_CYCLES):
            current_prompt = user_prompt + retry_warning

            try:
                response = await self._agentic_generate(
                    current_prompt,
                    system=system,
                    github_client=github_client,
                    context=context,
                )

                # ── False Positive Escape Hatch ──────────────────────────
                # If the LLM's analysis determines the finding is benign
                # (false positive, intended behavior, etc.), abort gracefully
                # instead of forcing code generation for a non-issue.
                if _FALSE_POSITIVE_RE.search(response):
                    logger.info(
                        "[CONTEXT SKIP] AI determined False Positive for %s:%d — "
                        "skipping fix generation.",
                        vuln.file,
                        vuln.line,
                    )
                    return None

                # ── Regex Interceptor ──────────────────────────────────
                if _FORBIDDEN_PATTERNS.search(response):
                    violations = _FORBIDDEN_PATTERNS.findall(response)[:5]
                    logger.warning(
                        "Lazy code detected (Cycle %d/%d). Violations: %s. Retrying...",
                        cycle + 1,
                        MAX_CYCLES,
                        violations,
                    )
                    retry_warning = (
                        "\n\nSYSTEM WARNING: Your previous attempt was REJECTED because "
                        "you used lazy placeholders or conversational text. "
                        "You MUST output the complete, functional code blocks this time. "
                        "FORBIDDEN patterns detected: "
                        + ", ".join(repr(v) for v in violations)
                        + ". Do NOT repeat them."
                    )
                    continue

                # ── Parse and validate ─────────────────────────────────
                parse_error_msg = None
                try:
                    changes = self._parse_changes(
                        response,
                        context,
                        extra_file_contents=_dependency_files or None,
                    )
                except GenerationError as ge:
                    parse_error_msg = str(ge)
                    changes = []

                if not changes:
                    logger.warning(
                        "No valid changes parsed for vuln at %s:%d (cycle %d)%s",
                        vuln.file,
                        vuln.line,
                        cycle + 1,
                        f" | Parser error: {parse_error_msg}" if parse_error_msg else "",
                    )
                    if parse_error_msg:
                        retry_warning = (
                            f"\n\nSYSTEM WARNING: Your previous output failed parsing with:\n"
                            f"  {parse_error_msg}\n"
                            f"Correct the JSON syntax and re-output ONLY the raw JSON structure. "
                            f"Do NOT add explanations or markdown fences."
                        )
                    else:
                        retry_warning = (
                            "\n\nSYSTEM WARNING: Your previous attempt produced no valid "
                            "search/replace edits. Make sure the `search` blocks match the "
                            "file content EXACTLY, character-for-character."
                        )
                    continue

                # ── Gag Order check ─────────────────────────────────────
                for change in changes:
                    for attr in ("new_content", "original_content"):
                        val = getattr(change, attr, "") or ""
                        if _GHOST_DISCLOSURE_RE.search(val):
                            logger.warning("Gag Order: AI disclosure in generated code. Aborting.")
                            raise GenerationError(
                                f"LLM output contains forbidden AI disclosure: {change.path}"
                            )

                # ── Build and return the Contribution ──────────────────
                commit_msg = f"fix(security): address {vuln.impact.lower()} in {vuln.file}"
                branch_name = (
                    f"fix/security-{vuln.file.replace('/', '-').replace('.', '-')}-{vuln.line}"
                )

                contribution = Contribution(
                    finding=Finding(
                        id=f"bh-{vuln.file}:{vuln.line}",
                        type=ContributionType.SECURITY_FIX,
                        severity=Severity.HIGH,
                        title=f"Security: {vuln.impact} in {vuln.file}",
                        description=vuln.snippet,
                        file_path=vuln.file,
                        line_start=vuln.line,
                        suggestion=vuln.fix,
                        impact_level=ImpactLevel.HIGH,
                    ),
                    contribution_type=ContributionType.SECURITY_FIX,
                    title=f"Security: {vuln.impact} in {vuln.file}",
                    description=vuln.poc,
                    changes=changes,
                    commit_message=commit_msg,
                    branch_name=branch_name,
                    generated_at=datetime.now(UTC),
                )
                return contribution

            except TemplateViolationError:
                retry_warning = (
                    "\n\nSYSTEM WARNING: Your previous attempt was REJECTED because "
                    "you used lazy placeholders or conversational text. "
                    "You MUST output the complete, functional code blocks this time."
                )
                continue
            except GenerationError:
                raise  # Re-raise gag order violations
            except Exception as exc:
                logger.error("Error in generation cycle %d: %s", cycle + 1, exc)
                retry_warning = (
                    f"\n\nSYSTEM WARNING: Your previous attempt crashed with: {exc}. "
                    f"Correct the issue and re-output ONLY the raw JSON structure."
                )
                continue

        # ── Hard Abort ──────────────────────────────────────────────────
        logger.error(
            "Failed to generate strict code after %d attempts for %s:%d. Aborting.",
            MAX_CYCLES,
            vuln.file,
            vuln.line,
        )
        raise RuntimeError(
            f"Failed to generate strict code after {MAX_CYCLES} attempts. "
            f"Aborting patch generation for {vuln.file}:{vuln.line}."
        )

