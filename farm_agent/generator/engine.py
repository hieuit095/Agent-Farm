# ── Module-level Gag Order regex — used by both _generate and fix_contribution_from_error ──
# ── Gag Order: Forbidden Security Words ─────────────────────────────────────
# These words SREAM "Automated Bot" and violate Responsible Disclosure policies.
# All security patches MUST be framed as "Reliability", "Robustness", "Error Handling".
_SECURITY_FORBIDDEN_RE = re.compile(
    r"(?i)\b(security|vulnerability|vulnerabilities|attack|exploit|malicious|threat|cve|"
    r"injection|path traversal|remote code execution|zero.day|zero-day)\b",
    re.IGNORECASE,
)

# ── Gag Order: Security Word Rephraser ────────────────────────────────────────
# Maps security-buzzwords to human-developer-friendly alternatives.
_SECURITY_REWRITE = [
    (
        re.compile(r"(?i)\bsecurity (issue|bug|vulnerability|flaw)\b", re.IGNORECASE),
        r"reliability concern",
    ),
    (re.compile(r"(?i)\bvulnerability\b", re.IGNORECASE), r"robustness gap"),
    (re.compile(r"(?i)\bsecurity fix\b", re.IGNORECASE), r"reliability improvement"),
    (re.compile(r"(?i)\bsecurity patch\b", re.IGNORECASE), r"robustness patch"),
    (
        re.compile(
            r"(?i)\bfix(?:ed)? (?:the )?security (?:issue|bug|vulnerability)\b", re.IGNORECASE
        ),
        r"improve robustness",
    ),
    (re.compile(r"(?i)\binjection\b", re.IGNORECASE), r"input boundary issue"),
    (re.compile(r"(?i)\bexploit\b", re.IGNORECASE), r"edge case"),
    (re.compile(r"(?i)\bmalicious\b", re.IGNORECASE), r"unexpected"),
    (re.compile(r"(?i)\battack vector\b", re.IGNORECASE), r"failure mode"),
    (re.compile(r"(?i)\bthreat\b", re.IGNORECASE), r"risk"),
    (re.compile(r"(?i)\bcve-\d+\b", re.IGNORECASE), r"[CVE reference removed]"),
    (re.compile(r"(?i)\bzero.day\b", re.IGNORECASE), r"unhandled edge case"),
    (re.compile(r"(?i)\bzero-day\b", re.IGNORECASE), r"unhandled edge case"),
    (re.compile(r"(?i)\bremote code execution\b", re.IGNORECASE), r"execution boundary violation"),
    (re.compile(r"(?i)\bpath traversal\b", re.IGNORECASE), r"path boundary violation"),
]


_GHOST_DISCLOSURE_RE = re.compile(
    r"(?i)(as an ai|ai generated|language model|openai|minimax|"
    r"automated bot|generated by ai|ai assistant|farm_agent|agent-farm|farmagent|"
    r"generated by this|this pr was generated|i was developed by)",
    re.IGNORECASE,
)

# Strip (not abort) — used for untrusted RAG-retrieved content
_STRIP_AI_RE = re.compile(
    r"(?i)(as an ai|ai generated|language model|openai|minimax|"
    r"automated bot|generated by ai|ai assistant|farm_agent|agent-farm|farmagent|"
    r"generated by this|this pr was generated|i was developed by)",
    re.IGNORECASE,
)


# ── XSS escape function — strips dangerous HTML/JavaScript patterns ─────────────────
_XSS_SCRIPT_RE = re.compile(r"<script[^>]*>.*?</script>", re.IGNORECASE | re.DOTALL)
_XSS_EVENT_HANDLER_RE = re.compile(r"\bon\w+\s*=", re.IGNORECASE)
_XSS_JAVASCRIPT_RE = re.compile(r"javascript\s*:", re.IGNORECASE)

_FORBIDDEN_PATTERNS = re.compile(
    r"\[.*code.*\]|\.{3}|<.*>|\bTBD\b|\bTODO\b|Insert.*here",
    re.IGNORECASE,
)

_FALSE_POSITIVE_RE = re.compile(
    r"(?:false\s+positive|no\s+fix\s+needed|intended\s+behavior|"
    r"not\s+a\s+vulnerability|this\s+is\s+not\s+a\s+security\s+issue|"
    r"benign\s+usage|acceptable\s+risk|no\s+action\s+required|"
    r"safe\s+by\s+design|by\s+design|this\s+finding\s+is\s+invalid|"
    r"not\s+exploitable|cannot\s+be\s+exploited|"
    r"deterministic\s+seed|benchmark\s+tool|test\s+only\s+usage)",
    re.IGNORECASE,
)


class GenerationResult:
    """Result from generate_from_dossier including false-positive tracking."""

    __slots__ = ("contributions", "false_positive_count")

    def __init__(self, contributions: list | None = None, false_positive_count: int = 0):
        self.contributions: list = contributions if contributions is not None else []
        self.false_positive_count: int = false_positive_count

    @property
    def all_false_positives(self) -> bool:
        return self.false_positive_count > 0 and len(self.contributions) == 0


